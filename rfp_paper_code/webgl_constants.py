import os as _os

_unknown_ext_path = None
_seen_unknown = set()

def set_unknown_extensions_path(output_folder):
  """Set the output path for unknown WebGL extensions logging."""
  global _unknown_ext_path
  _unknown_ext_path = _os.path.join(output_folder, "unknown_webgl_extensions.txt")

def log_unknown_extensions(unknown, source):
  """Append unknown extensions to the log file (if path is set). Deduplicates in-memory."""
  if not _unknown_ext_path or not unknown:
    return
  new = unknown - _seen_unknown
  if not new:
    return
  _seen_unknown.update(new)
  with open(_unknown_ext_path, "a") as f:
    for ext in sorted(new):
      f.write(f"{ext}\t{source}\n")
